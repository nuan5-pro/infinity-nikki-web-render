import { DoubleSide, MeshStandardMaterial, ShaderLib, Texture, type WebGLRenderer } from 'three';
import { describe, expect, it } from 'vitest';
import { applyFoliageTransmission } from '../../src/materials/foliage/foliageTransmission.js';
import { applyEnvironmentLighting, setEnvironmentDiffuseWeight } from '../../src/runtime/environmentLighting.js';
import { applyShadingQuality } from '../../src/runtime/shadingQuality.js';

describe('source-declared foliage transmission', () => {
	it.each(['original', 'performance', 'economy'] as const)('keeps scene SH, shadowed direct lights and AO order in %s', quality => {
		const material = new MeshStandardMaterial({ side: DoubleSide });
		material.userData.render = { foliageTransmission: { model: 'mask-step', colorA: [.15, .2, .3], colorB: [.15, .2, .3], baseColorInfluence: 3, stepMask: 1, threshold: .4, singleSided: 1 } };
		applyFoliageTransmission(material);
		const hook = material.onBeforeCompile;
		applyFoliageTransmission(material);
		expect(material.onBeforeCompile).toBe(hook);
		applyEnvironmentLighting(material);
		applyShadingQuality(material, quality, 'standard');
		const renderer = {} as WebGLRenderer;
		setEnvironmentDiffuseWeight(renderer, 0);
		const shader = { uniforms: {} as Record<string, { value: unknown }>, vertexShader: ShaderLib.standard.vertexShader, fragmentShader: ShaderLib.standard.fragmentShader };
		material.onBeforeCompile(shader as never, renderer);
		const fs = shader.fragmentShader;
		expect(fs).toContain('getLightProbeIrradiance(lightProbe, -geometryNormal)');
		expect(fs).toContain('getHemisphereLightIrradiance(hemisphereLights[i], -geometryNormal)');
		expect(fs).toContain('getIBLIrradiance(-geometryNormal)');
		expect(fs).toContain('float a2=0.36;');
		expect(fs).toContain('if ( editorEnvironmentDiffuseWeight == 0.0 ) return vec3( 0.0 );');
		expect(fs.indexOf('directLight.color *=')).toBeLessThan(fs.indexOf('reflectedLight.directDiffuse += foliageDirectTransmission'));
		expect(fs.indexOf('reflectedLight.indirectDiffuse += max(foliageBackIrradiance')).toBeLessThan(fs.indexOf('#include <aomap_fragment>'));
		expect(shader.uniforms.foliageTransmissionBaseColor.value).toBe(3);
		expect(fs).not.toContain('clamp(foliageTransmissionBaseColor');
		expect(fs).toContain('foliageTransmissionAlbedo=sampledDiffuseColor.rgb;');
		expect(fs).toContain('(1.0-foliageSssSign*foliageTransmissionParams.z)');
		expect(fs).not.toContain('sampler2D foliageTransmissionMask');
		material.dispose();
	});
	it('samples the original mask G and preserves the source reversed threshold step', () => {
		const material = new MeshStandardMaterial();
		material.userData.render = { foliageTransmission: { model: 'mask-step', colorA: [.1, .2, .3], colorB: [.4, .5, .6], baseColorInfluence: 0, stepMask: 1, threshold: .4, singleSided: 0, mask: { role: 'O1', uvScale: 2 } } };
		expect(() => applyFoliageTransmission(material)).toThrow('source mask');
		const mask = new Texture();
		applyFoliageTransmission(material, mask);
		const shader = { uniforms: {} as Record<string, { value: unknown }>, vertexShader: ShaderLib.standard.vertexShader, fragmentShader: ShaderLib.standard.fragmentShader };
		material.onBeforeCompile(shader as never, {} as WebGLRenderer);
		expect(shader.uniforms.foliageTransmissionMask.value).toBe(mask);
		expect(shader.fragmentShader).toContain('step(foliageSssMask.g,foliageTransmissionParams.y)');
		expect(shader.fragmentShader).toContain('textureGrad(foliageTransmissionMask,foliageSssUv,foliageSssDx,foliageSssDy)');
		expect(shader.fragmentShader.indexOf('dFdx(foliageSssUv)')).toBeLessThan(shader.fragmentShader.indexOf('#include <alphatest_fragment>'));
		expect(shader.vertexShader).toContain('vFoliageTransmissionUv=uv;');
		mask.dispose();
		material.dispose();
	});
	it.each(['original', 'performance', 'economy'] as const)('keeps ST9 source red, face selection and mask intensity in %s', quality => {
		const material = new MeshStandardMaterial();
		material.userData.render = { foliageTransmission: { model: 'face-mask', colorA: [.1, .2, .3], colorB: [.1, .2, .3], baseColorInfluence: 1, mask: { role: 'O1', uvScale: 1 }, vertex: { base: [0, 0, 0], min: 0, max: 1, power: 20 } } };
		const mask = new Texture();
		applyFoliageTransmission(material, mask);
		applyShadingQuality(material, quality, 'foliage');
		const shader = { uniforms: {}, vertexShader: ShaderLib.standard.vertexShader, fragmentShader: ShaderLib.standard.fragmentShader };
		material.onBeforeCompile(shader as never, {} as WebGLRenderer);
		expect(shader.vertexShader).toContain('vFoliageTransmissionRed=foliageRed;');
		expect(shader.fragmentShader).toContain('foliageSssMask.g*mix(foliageTransmissionColorB,foliageTransmissionColorA,clamp(foliageSssSign,0.0,1.0))');
		expect(shader.fragmentShader).toContain('foliageSssQ>0.0?min(pow(foliageSssQ,foliageTransmissionVertexParams.z),1.0):0.0');
		expect(shader.fragmentShader).not.toContain('(1.0-foliageSssSign*foliageTransmissionParams.z)');
		mask.dispose(); material.dispose();
	});
	it('does not alter materials without an explicit transmission declaration', () => {
		const material = new MeshStandardMaterial({ side: DoubleSide });
		const hook = material.onBeforeCompile;
		applyFoliageTransmission(material);
		expect(material.onBeforeCompile).toBe(hook);
		material.dispose();
	});
	it('uses the captured Grass blue mask without assuming an albedo influence', () => {
		const material = new MeshStandardMaterial();
		material.userData.render = { foliageTransmission: { model: 'face-mask', colorA: [.1, .2, .3], colorB: [.4, .5, .6], baseColorInfluence: 0, mask: { role: 'O1', uvScale: 1, channel: 'b' } } };
		const mask = new Texture();
		applyFoliageTransmission(material, mask);
		const shader = { uniforms: {} as Record<string, { value: unknown }>, vertexShader: ShaderLib.standard.vertexShader, fragmentShader: ShaderLib.standard.fragmentShader };
		material.onBeforeCompile(shader as never, {} as WebGLRenderer);
		expect(shader.fragmentShader).toContain('foliageTransmission=foliageSssMask.b*mix(');
		expect(shader.uniforms.foliageTransmissionBaseColor.value).toBe(0);
		expect(shader.fragmentShader).not.toContain('foliageTransmissionAlbedo=sampledDiffuseColor.rgb;');
		mask.dispose(); material.dispose();
	});
	it('samples an independent static albedo endpoint without replacing the visible map', () => {
		const visible = new Texture(), source = new Texture();
		const material = new MeshStandardMaterial({ map: visible });
		material.userData.render = { foliageTransmission: { model: 'mask-step', colorA: [.1, .2, .3], colorB: [.1, .2, .3], baseColorInfluence: 1, stepMask: 1, threshold: 0, singleSided: 0, albedo: { role: 'D1', uvScale: 2 } } };
		applyFoliageTransmission(material, undefined, source);
		const shader = { uniforms: {} as Record<string, { value: unknown }>, vertexShader: ShaderLib.standard.vertexShader, fragmentShader: ShaderLib.standard.fragmentShader };
		material.onBeforeCompile(shader as never, {} as WebGLRenderer);
		expect(material.map).toBe(visible);
		expect(shader.uniforms.foliageTransmissionAlbedoMap.value).toBe(source);
		expect(shader.fragmentShader).toContain('textureGrad(foliageTransmissionAlbedoMap,foliageSssAlbedoUv,foliageSssAlbedoDx,foliageSssAlbedoDy).rgb');
		expect(shader.fragmentShader.indexOf('dFdx(foliageSssAlbedoUv)')).toBeLessThan(shader.fragmentShader.indexOf('#include <alphatest_fragment>'));
		expect(shader.fragmentShader).not.toContain('foliageTransmissionAlbedo=sampledDiffuseColor.rgb;');
		material.dispose(); visible.dispose(); source.dispose();
	});
});
